// Build: what `jebart build` writes (build.py). The runtime data, mod/hooks/pixel-art.ts (write_ts): the palette, the
// colour names, the 3x5 font and every sprite's frames, its text byte-identical to the Python's, including json.dumps'
// `, ` and `: ` separators and its \uXXXX escapes. Then sheets/<sprite>.png (every frame side by side, 4x, for review),
// gifs/<sprite>.gif (animated previews, animated sprites only), the three scene mockups, and the summary line.
import Foundation

/// json.dumps of a str (ensure_ascii=True).
func pyJsonString(_ s: String) -> String {
    var out = "\""
    for u in s.unicodeScalars {
        switch u {
        case "\"": out += "\\\""
        case "\\": out += "\\\\"
        case "\n": out += "\\n"
        case "\r": out += "\\r"
        case "\t": out += "\\t"
        case "\u{08}": out += "\\b"
        case "\u{0C}": out += "\\f"
        default:
            if u.value >= 0x20 && u.value < 0x7F {
                out.unicodeScalars.append(u)
            } else {
                for unit in String(u).utf16 { out += String(format: "\\u%04x", unit) }
            }
        }
    }
    return out + "\""
}

/// The text of pixel-art.ts. `font` is farm.py's FONT in its own order; only single-character glyphs are exported.
func tsText(_ sprites: [Sprite], font: [(String, String)]) -> String {
    let colours = ["0"] + palette.map { String((Int($0.r) << 16) | (Int($0.g) << 8) | Int($0.b)) }
    let names = paletteNames.enumerated().map { "\(pyJsonString($1)): \($0)" }
    let glyphs = font.filter { $0.0.unicodeScalars.count == 1 }.map { "\(pyJsonString($0.0)): \(pyJsonString($0.1))" }
    var body = [
        "// Generated by art/src/build.py: do not edit by hand.",
        "// One shared palette (index 0 is transparent) and every sprite as",
        "// run-length frames: base64 of (run, paletteIndex) byte pairs, row-major.",
        "",
        "export const PIXEL_PALETTE: readonly number[] = [\(colours.joined(separator: ", "))]",
        "",
        "// Palette indices by colour name, for anything the mod draws itself.",
        "export const PIXEL_COLOUR: Readonly<Record<string, number>> = {\(names.joined(separator: ", "))}",
        "",
        "// 3x5 font: 15 bits per glyph, row-major, \"1\" = ink.",
        "export const PIXEL_FONT: Readonly<Record<string, string>> = {\(glyphs.joined(separator: ", "))}",
        "",
        "export type PixelSprite = { w: number; h: number; frames: readonly string[] }",
        "",
        "export const PIXEL_SPRITES: Readonly<Record<string, PixelSprite>> = {",
    ]
    // a dict in the Python: a repeated name keeps its first place and its last frames
    var order: [String] = []
    var byName: [String: (w: Int, h: Int, frames: [String])] = [:]
    for s in sprites {
        if byName[s.name] == nil { order.append(s.name) }
        byName[s.name] = encode(s)
    }
    for name in order {
        guard let e = byName[name] else { continue }
        let frames = e.frames.map { "'\($0)'" }.joined(separator: ", ")
        body.append("  '\(name)': { w: \(e.w), h: \(e.h), frames: [\(frames)] },")
    }
    body.append("}")
    return body.joined(separator: "\n") + "\n"
}

/// Writes pixel-art.ts and returns its size in bytes.
func writeTs(_ sprites: [Sprite], font: [(String, String)], to path: String) throws -> Int {
    let data = Data(tsText(sprites, font: font).utf8)
    try data.write(to: URL(fileURLWithPath: path))
    return data.count
}

/// sheets/<sprite>.png: all frames side by side, scaled for viewing.
func sheetPng(_ sprite: Sprite, scale: Int = 4) -> [UInt8] {
    let (w, h) = sprite.size
    let sheet = Raster(w * sprite.frames.count, h)
    for (i, frame) in sprite.frames.enumerated() { sheet.alphaComposite(frame, at: i * w, 0) }
    return pngEncode(sheet.resized(sheet.width * scale, sheet.height * scale), level: 9)
}

/// build.py's main: sheets, gifs, runtime data and scenes under `outDir` (the data at `tsPath`); returns the stdout
/// lines: the summary, then the scene paths.
func buildAll(outDir: String, tsPath: String) throws -> [String] {
    let fm = FileManager.default
    try fm.createDirectory(atPath: outDir + "/sheets", withIntermediateDirectories: true)
    try fm.createDirectory(atPath: outDir + "/gifs", withIntermediateDirectories: true)
    let sprites = allSprites()
    guard Set(sprites.map { $0.name }).count == sprites.count else { throw GifError(description: "duplicate sprite names") }
    var gifTotal = 0
    for s in sprites {
        try Data(sheetPng(s)).write(to: URL(fileURLWithPath: "\(outDir)/sheets/\(s.name).png"))
        if let gif = try gifBytes(frames: s.frames, ms: s.ms) {
            try Data(gif).write(to: URL(fileURLWithPath: "\(outDir)/gifs/\(s.name).gif"))
            gifTotal += gif.count
        }
    }
    let size = try writeTs(sprites, font: farmFont, to: tsPath)
    let shots = try writeMockups(sprites, to: outDir)
    let frames = sprites.reduce(0) { $0 + $1.frames.count }
    return ["\(sprites.count) sprites, \(frames) frames, \(paletteNames.count - 1) colours; runtime data \(size) bytes; gifs \(gifTotal) bytes"] + shots
}
