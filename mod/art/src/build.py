"""Build Jeb's pixel art.

  python build.py OUT_DIR TS_FILE

writes, under OUT_DIR:
  sheets/<sprite>.png  every frame side by side, 4x, for review
  gifs/<sprite>.gif    optimized animated previews (animated sprites only)
  scene-*.png          full-band mockups at 150 columns, 3x
and TS_FILE: the runtime sprite data (shared palette + RLE frames) the mod
composites into the band's Image.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from PIL import Image, ImageDraw

from characters import blue_sprites, jeb_sprites, visitor_sprites
from farm import FONT, farm_sprites, text
from nature import unlock_sprites
from pixel import CELL_H, CELL_W, NAMES, PALETTE, Sprite, encode, rgb, save_gif, save_sheet


def all_sprites() -> list[Sprite]:
    return jeb_sprites() + blue_sprites() + visitor_sprites() + farm_sprites() + unlock_sprites()


def write_ts(sprites: list[Sprite], path: Path) -> int:
    palette = [0] + [(r << 16) | (g << 8) | b for r, g, b in PALETTE.values()]
    data = {s.name: encode(s) for s in sprites}
    body = [
        '// Generated by art/src/build.py: do not edit by hand.',
        '// One shared palette (index 0 is transparent) and every sprite as',
        '// run-length frames: base64 of (run, paletteIndex) byte pairs, row-major.',
        '',
        f'export const PIXEL_PALETTE: readonly number[] = {json.dumps(palette)}',
        '',
        '// Palette indices by colour name, for anything the mod draws itself.',
        f'export const PIXEL_COLOUR: Readonly<Record<string, number>> = {json.dumps({n: i for i, n in enumerate(NAMES)})}',
        '',
        '// 3x5 font: 15 bits per glyph, row-major, "1" = ink.',
        f'export const PIXEL_FONT: Readonly<Record<string, string>> = {json.dumps({k: v for k, v in FONT.items() if len(k) == 1})}',
        '',
        'export type PixelSprite = { w: number; h: number; frames: readonly string[] }',
        '',
        'export const PIXEL_SPRITES: Readonly<Record<string, PixelSprite>> = {',
    ]
    for name, sprite in data.items():
        frames = ', '.join(f"'{f}'" for f in sprite['frames'])
        body.append(f"  '{name}': {{ w: {sprite['w']}, h: {sprite['h']}, frames: [{frames}] }},")
    body.append('}')
    path.write_text('\n'.join(body) + '\n')
    return path.stat().st_size


# --------------------------------------------------------------- mockups ----

class Scene:
    """A band-sized canvas. Columns x 4 by rows x 8 pixels."""

    def __init__(self, sprites: dict[str, Sprite], cols: int = 150, rows: int = 6, night: bool = False):
        self.s = sprites
        self.w, self.h = cols * CELL_W, rows * CELL_H
        sky = (34, 40, 70) if night else (150, 200, 235)
        self.img = Image.new('RGBA', (self.w, self.h), (*sky, 255))
        self.d = ImageDraw.Draw(self.img)
        self.ground = self.h - 9  # top of the grass strip

    def stamp(self, name: str, x: int, bottom: int | None = None, frame: int = 0, y: int | None = None):
        sprite = self.s[name]
        image = sprite.frames[frame % len(sprite.frames)]
        top = y if y is not None else (bottom if bottom is not None else self.ground) - image.height
        self.img.alpha_composite(image, (x, top))
        return image.width

    def land(self):
        d = self.d
        d.rectangle([0, self.ground, self.w, self.ground + 1], fill=rgb('grass'))
        d.rectangle([0, self.ground + 2, self.w, self.h], fill=rgb('road'))
        for x in range(0, self.w, 12):
            d.line([x, self.h - 3, x + 5, self.h - 3], fill=rgb('road_dark'))

    def plots(self, stages: dict[str, list[int]], labels: dict[str, str]):
        x = 2
        for crop in ('tobacco', 'corn'):
            self.d.rectangle([x, self.ground - 2, x + 49, self.ground], fill=rgb('soil'))
            for i, stage in enumerate(stages[crop]):
                self.stamp(f'{crop}-{stage}', x + 1 + i * 6, self.ground)
            text(self.d, x + 2, self.h - 7, labels[crop], 'white')
            x += 56
        for i, stage in enumerate(stages['apples'][:4]):
            self.stamp(f'apple-{stage}', x + i * 11, self.ground)
        text(self.d, x + 2, self.h - 7, labels['apples'], 'white')
        return x + 46


def mockups(sprites: list[Sprite], out: Path) -> list[Path]:
    by = {s.name: s for s in sprites}
    stages = {'tobacco': [3, 3, 2, 2, 1, 3, 2, 1], 'corn': [3, 2, 3, 1, 2, 3, 0, 1], 'apples': [3, 3, 2, 1]}
    labels = {'tobacco': 'TOBACCO 6', 'corn': 'CORN 5', 'apples': 'APPLES 118'}
    paths = []

    def right_cluster(sc: Scene, jeb: str, night: bool, lit: bool, jeb_frame: int = 0, extras=()):
        house = 'house-night' if night else 'house'
        hx = sc.w - 51
        sc.stamp(house, hx, sc.ground + 1)
        sc.stamp('smoke', hx + 34, y=0, frame=1)
        sx = hx - 40
        sc.stamp('still', sx, sc.ground)
        sc.stamp('fire' if lit else 'embers', sx + 3, sc.ground, frame=jeb_frame)
        if lit:
            sc.stamp('steam', sx + 7, y=0, frame=jeb_frame)
        jx = sx - 22
        sc.stamp(jeb, jx, sc.ground + 1, frame=jeb_frame)
        sc.stamp('blue-nap' if night else 'blue-wag', jx - 20, sc.ground + 1)
        for name, x, y in extras:
            sc.stamp(name, x, y=y)
        return jx

    def middle(sc: Scene, start: int, night: bool, quilt: str, lanterns: int):
        stack = [('icon-lumber', 3), ('icon-stone', 3), ('icon-straw', 2), ('icon-iron', 2), ('icon-twist', 1)]
        x = start + 6
        line_y = 4
        sc.d.line([x - 2, line_y, x + len(quilt) * 6 + 1, line_y], fill=rgb('wood_dark'))
        for i, code in enumerate(quilt):
            sc.stamp(f'quilt-{code}', x + i * 6, y=line_y + 1)
        for col, (name, height) in enumerate(stack):
            for k in range(height):
                sc.stamp(name, x + col * 9, sc.ground - k * 8)
        sign = 'sign-night' if night else 'sign'
        sgx = x + len(stack) * 9 + 8
        sc.stamp(sign, sgx, sc.ground + 1)
        for i in range(lanterns):
            sc.stamp('lantern', sgx + 14 + i * 8, y=1)
        return sgx

    # Day, busy: hoeing, hired hands, the truck on the road, rain on the corn.
    sc = Scene(by)
    sc.land()
    end = sc.plots(stages, labels)
    sc.stamp('hand-work', 14, sc.ground + 1, frame=0)
    sc.stamp('hand-work', 72, sc.ground + 1, frame=1)
    for x in range(58, 108, 7):
        sc.d.line([x, 6, x - 1, 9], fill=rgb('drop'))
        sc.d.line([x + 3, 13, x + 2, 16], fill=rgb('drop'))
    sc.stamp('cloud-dark', 66, y=0)
    middle(sc, end, False, 'NBGGPBRG', 0)
    jx = right_cluster(sc, 'jeb-hoe', False, True)
    sc.stamp('sun', jx - 60, y=2)
    sc.stamp('truck-jars', 250, sc.h)
    sc.stamp('dust', 240, sc.h - 2)
    paths.append(save_mock(sc, out / 'scene-day-busy.png'))

    # Evening: banjo on the porch, lanterns for the other camps, still lit.
    sc = Scene(by)
    sc.land()
    end = sc.plots(stages, labels)
    sc.stamp('cow', 300, sc.h)
    middle(sc, end, False, 'NBGGPBRGYB', 2)
    jx = right_cluster(sc, 'jeb-banjo', False, True)
    sc.stamp('note', jx - 6, y=6)
    sc.stamp('note', jx - 12, y=1)
    paths.append(save_mock(sc, out / 'scene-evening-banjo.png'))

    # Night: asleep on the porch, moon and fireflies, windows lit, embers.
    sc = Scene(by, night=True)
    sc.land()
    end = sc.plots(stages, labels)
    for x, y in ((30, 3), (90, 6), (140, 2), (200, 5), (330, 4), (420, 2), (470, 7)):
        sc.d.point((x, y), fill=rgb('night_star'))
    for x, y in ((20, 20), (64, 24), (110, 18)):
        sc.stamp('firefly', x, y=y)
    middle(sc, end, True, 'NBGGPBRGYB', 2)
    jx = right_cluster(sc, 'jeb-sleep', True, False)
    sc.stamp('moon', jx - 60, y=2, frame=2)
    sc.stamp('zz', jx + 14, y=0)
    sc.stamp('mothman', 160, y=8)
    paths.append(save_mock(sc, out / 'scene-night.png'))
    return paths


def save_mock(sc: Scene, path: Path, scale: int = 3) -> Path:
    # Show the cell aspect the terminal uses: each 4x8 block is one cell.
    sc.img.resize((sc.w * scale, sc.h * scale), Image.NEAREST).save(path, optimize=True)
    return path


def main():
    out, ts = Path(sys.argv[1]), Path(sys.argv[2])
    (out / 'sheets').mkdir(parents=True, exist_ok=True)
    (out / 'gifs').mkdir(parents=True, exist_ok=True)
    sprites = all_sprites()
    names = [s.name for s in sprites]
    assert len(names) == len(set(names)), 'duplicate sprite names'
    for s in sprites:
        save_sheet(s, out / 'sheets')
        save_gif(s, out / 'gifs')
    size = write_ts(sprites, ts)
    shots = mockups(sprites, out)
    gif_bytes = sum(p.stat().st_size for p in (out / 'gifs').glob('*.gif'))
    print(f'{len(sprites)} sprites, {sum(len(s.frames) for s in sprites)} frames, '
          f'{len(NAMES) - 1} colours; runtime data {size} bytes; gifs {gif_bytes} bytes')
    for p in shots:
        print(p)


if __name__ == '__main__':
    main()
